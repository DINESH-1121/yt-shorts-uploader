/**
 * qualityChecker.js — Pre-upload video quality & compliance validator using OpenCode models.
 *
 * Enforces two strict quality criteria before ANY video is uploaded to YouTube:
 * 1. AI Generated Slop: If the entire video is AI-generated slop (e.g., completely synthetic
 *    AI video generation like Sora/Runway/Kling/Pika, morphing AI loops, talking AI avatars,
 *    or low-effort AI brainrot/slideshows), REJECT. Authentic gaming gameplay and real tech
 *    hardware demos are NOT slop.
 * 2. Person Name: If ANY person's name appears anywhere in the video (title, description,
 *    uploader, tags, subtitles/transcript, or visible on-screen text/watermarks in video frames),
 *    REJECT. Real human names, celebrities, streamers, YouTubers, influencers, or creator names.
 *
 * Validated with OpenCode models via aiClient.
 */

const fs = require('fs');
const path = require('path');
const os = require('os');
const { execFile } = require('child_process');
const aiClient = require('./aiClient');
const { probeVideo } = require('./shortsFormatter');

// Resolve ffmpeg binary path
const FFMPEG_BIN = process.env.FFMPEG_PATH || (
  fs.existsSync('/opt/homebrew/bin/ffmpeg')
    ? '/opt/homebrew/bin/ffmpeg'
    : (fs.existsSync('/usr/local/bin/ffmpeg') ? '/usr/local/bin/ffmpeg' : 'ffmpeg')
);

/**
 * Extracts representative sample frames across the video as temporary JPEG images.
 * Samples at 20%, 50%, and 80% of video duration.
 */
async function extractSampleFrames(videoPath, count = 3) {
  if (!fs.existsSync(videoPath)) return [];

  const info = await probeVideo(videoPath);
  const duration = info?.duration || 10;
  const frames = [];
  const tempPrefix = path.join(os.tmpdir(), `qc_${process.pid}_${Date.now()}_`);

  const times = count === 1
    ? [Math.max(0.5, duration * 0.5)]
    : [
        Math.max(0.5, Math.min(duration - 0.5, duration * 0.2)),
        Math.max(0.5, Math.min(duration - 0.5, duration * 0.5)),
        Math.max(0.5, Math.min(duration - 0.5, duration * 0.8))
      ];

  for (let i = 0; i < times.length; i++) {
    const framePath = `${tempPrefix}frame_${i}.jpg`;
    try {
      await new Promise((resolve, reject) => {
        execFile(FFMPEG_BIN, [
          '-y',
          '-ss', String(times[i]),
          '-i', videoPath,
          '-frames:v', '1',
          '-q:v', '2',
          framePath
        ], { timeout: 15000 }, (err) => {
          if (err) reject(err);
          else resolve();
        });
      });
      if (fs.existsSync(framePath)) {
        frames.push(framePath);
      }
    } catch (err) {
      console.warn(`[QualityChecker] Could not extract frame at ${times[i]}s:`, err.message);
    }
  }

  return frames;
}

/**
 * Extracts any embedded subtitle stream from the video file
 */
function extractSubtitles(videoPath) {
  return new Promise((resolve) => {
    if (!fs.existsSync(videoPath)) return resolve('');
    const srtPath = path.join(os.tmpdir(), `qc_subs_${process.pid}_${Date.now()}.srt`);
    execFile(FFMPEG_BIN, [
      '-y',
      '-i', videoPath,
      '-map', '0:s:0',
      srtPath
    ], { timeout: 10000 }, (err) => {
      if (err || !fs.existsSync(srtPath)) {
        return resolve('');
      }
      try {
        const text = fs.readFileSync(srtPath, 'utf8').trim();
        try { fs.unlinkSync(srtPath); } catch {}
        resolve(text);
      } catch {
        resolve('');
      }
    });
  });
}

/**
 * Local heuristic validator used as a safety fallback if all OpenCode models are unreachable
 */
function heuristicQualityCheck({ title = '', description = '', uploader = '' }) {
  const combined = `${title} ${description} ${uploader}`.toLowerCase();

  // Obvious AI slop signals
  const slopPatterns = [
    /\b(ai generated|sora ai|midjourney video|runway gen|pika labs|kling ai|ai animation|ai brainrot|synthetic video|completely generated by ai)\b/i,
    /#(sora|runway|pika|kling|aigenerated|generativeai)\b/i
  ];
  const isSlop = slopPatterns.some(p => p.test(combined));

  // Prominent creator/celebrity names
  const knownPersons = [
    'mrbeast', 'mr beast', 'kai cenat', 'ishowspeed', 'speed', 'elon musk', 'joe rogan',
    'jake paul', 'logan paul', 'pewdiepie', 'mark zuckerberg', 'donald trump', 'cristiano ronaldo',
    'ronaldo', 'messi', 'lionel messi', 'pokimane', 'ninja', 'xqc', 'andrew tate', 'adin ross'
  ];
  const detectedPerson = knownPersons.find(name => {
    const regex = new RegExp(`\\b${name}\\b`, 'i');
    return regex.test(combined);
  });

  if (isSlop) {
    return {
      decision: 'REJECT',
      isAiSlop: true,
      hasPersonName: !!detectedPerson,
      detectedNames: detectedPerson ? [detectedPerson] : [],
      reason: 'Rejected by heuristic safety check: Video metadata indicates 100% synthetic AI-generated content (AI slop).'
    };
  }

  if (detectedPerson) {
    return {
      decision: 'REJECT',
      isAiSlop: false,
      hasPersonName: true,
      detectedNames: [detectedPerson],
      reason: `Rejected by heuristic safety check: Detected person name "${detectedPerson}" in video metadata.`
    };
  }

  return {
    decision: 'PASS',
    isAiSlop: false,
    hasPersonName: false,
    detectedNames: [],
    reason: 'Passed heuristic safety check (No AI slop or known person names found in metadata).'
  };
}

/**
 * Main quality check executor:
 * Validates a video using OpenCode models with attached video frames and complete metadata.
 *
 * @param {object} params
 * @param {string} params.videoPath       Local path to the formatted/downloaded MP4 video
 * @param {object} params.metadata        Video metadata { title, description, uploader, tags, ... }
 * @param {string} [params.model]         Preferred OpenCode model ref
 * @param {function} [params.onProgress]  Progress notification callback
 * @returns {Promise<{ decision: 'PASS'|'REJECT', isAiSlop: boolean, hasPersonName: boolean, detectedNames: string[], reason: string, usedModel: string }>}
 */
async function checkVideoQuality({ videoPath, metadata = {}, model, onProgress }) {
  onProgress?.('🔍 Quality Checker: Extracting sample frames from video for visual analysis...');
  console.log(`[QualityChecker] Starting validation on video: "${metadata.title || videoPath}"`);

  let sampleFrames = [];
  let subtitles = '';

  try {
    const [frames, subs] = await Promise.all([
      extractSampleFrames(videoPath, 3),
      extractSubtitles(videoPath)
    ]);
    sampleFrames = frames;
    subtitles = subs;
  } catch (err) {
    console.warn('[QualityChecker] Error gathering visual frames/subtitles:', err.message);
  }

  const prompt = `You are an elite video quality, safety, and compliance validator for a high-standard YouTube Shorts channel.
Your job is to strictly evaluate this video and decide whether it is ALLOWED to be uploaded to YouTube or must be REJECTED.

You are evaluating:
1. Video Title: ${metadata.title || 'N/A'}
${metadata.originalTitle && metadata.originalTitle !== metadata.title ? `Original Source Title: ${metadata.originalTitle}` : ''}
2. Video Uploader / Channel: ${metadata.uploader || 'N/A'}
3. Video Description: ${metadata.description || 'N/A'}
4. Video Tags / Hashtags: ${Array.isArray(metadata.tags) ? metadata.tags.join(', ') : (metadata.tags || 'N/A')}
5. Subtitles / Transcript: ${subtitles ? subtitles.slice(0, 500) : 'None extracted'}
6. Visual Keyframes: ${sampleFrames.length} representative frame(s) extracted from the video and attached to this request.

============================================================
CRITICAL REJECTION RULES (Read carefully and enforce strictly):
============================================================

RULE 1: REJECT IF THE ENTIRE VIDEO IS AI GENERATED SLOP
- What IS AI generated slop:
  * 100% synthetic AI-generated video loops or hallucinations (e.g., Sora, Runway Gen-2/3, Kling, Pika, Haiper, Luma, morphing uncanny AI objects/scenes).
  * Synthetic AI-generated slideshows with robotic AI voiceover reading fake facts, Reddit stories, or generic AI motivational scripts.
  * AI-generated deepfake avatars talking to the camera, or weird surreal AI brainrot/memes (e.g., dancing AI animals/babies, fake AI creature transformations).
  * Low-effort, mass-generated synthetic spam devoid of genuine human artistry, real gameplay, or authentic video.
- What is NOT AI generated slop:
  * Real video game captures/gameplay (e.g. GTA 5/6, Minecraft, Fortnite, Valorant, Call of Duty, Unreal Engine 5 tech demos, Elden Ring, Black Myth: Wukong, etc.). High-end 3D video game graphics and CGI in video games are authentic gaming clips, NOT AI slop.
  * Authentic tech reviews, real gadget hardware demos, actual robotics, physical product reveals.
  * Real human animations, artistic edits, or real-life clips.
- IF THE ENTIRE VIDEO IS AI-GENERATED SLOP -> MUST REJECT! Set "isAiSlop": true.

RULE 2: REJECT IF ANY PERSON NAME IS IN THE VIDEO
- What IS a person name:
  * Any real human name or public figure name: celebrities, streamers, YouTubers, influencers, politicians, athletes, actors, historical persons, or real individual person names (e.g. "MrBeast", "Kai Cenat", "IShowSpeed", "Elon Musk", "Joe Rogan", "Jake Paul", "Logan Paul", "PewDiePie", "Mark Zuckerberg", "Donald Trump", "Cristiano Ronaldo", "Lionel Messi", "Pokimane", "Ninja", "xQc", "Andrew Tate", "John Doe", "Sarah", "Md Dilshad", "Roqeebat Jimoh", etc.).
  * Look closely in:
    a) Video Title
    b) Video Description
    c) Uploader / Creator name
    d) Visual text / burnt-in captions / watermarks / streamer camera overlays in the attached frames
    e) Spoken names in subtitles / transcript
- What is NOT considered a person name:
  * Established game franchise / studio names (e.g. "Grand Theft Auto", "Rockstar Games", "Mojang", "Epic Games", "Sony", "PlayStation", "Xbox").
  * Fictional video game characters strictly within game lore (e.g. "Trevor Philips", "Master Chief", "Arthur Morgan", "Steve"), UNLESS attached to a real streamer/creator (e.g. "Kai Cenat plays Trevor" has a person name).
- IF ANY PERSON NAME IS FOUND -> MUST REJECT! Set "hasPersonName": true and list every name in "detectedNames".

============================================================
DECISION LOGIC:
============================================================
- If isAiSlop is true OR hasPersonName is true:
  "decision": "REJECT"
  "reason": Detailed, explicit explanation of why it was rejected.
- If BOTH rules pass (no AI slop AND no person names anywhere):
  "decision": "PASS"
  "reason": Detailed explanation of why the video passed quality check.

Respond ONLY with valid JSON in this exact structure:
{
  "decision": "PASS",
  "isAiSlop": false,
  "hasPersonName": false,
  "detectedNames": [],
  "reason": "Explanation of validation findings"
}`;

  onProgress?.('🧠 Quality Checker: Validating with OpenCode models (checking for AI slop & person names)...');

  try {
    const { result, usedModel } = await aiClient.generateJSON(prompt, {
      model: model || 'opencode/nemotron-3.5-super-vl-free',
      task: 'quality_check',
      files: sampleFrames,
      timeoutMs: 60000
    });

    const isAiSlop = Boolean(result.isAiSlop);
    const hasPersonName = Boolean(result.hasPersonName || (Array.isArray(result.detectedNames) && result.detectedNames.length > 0));
    const shouldReject = isAiSlop || hasPersonName || String(result.decision).toUpperCase() === 'REJECT';

    const decision = shouldReject ? 'REJECT' : 'PASS';
    const reason = result.reason || (
      shouldReject
        ? `Video rejected: ${isAiSlop ? 'AI-generated slop detected. ' : ''}${hasPersonName ? `Person name(s) detected: ${result.detectedNames?.join(', ')}. ` : ''}`
        : 'Quality check passed: Video contains authentic content with no AI slop and no person names.'
    );

    console.log(`[QualityChecker] ${decision === 'PASS' ? '✅' : '🛑'} Validated by ${usedModel}: ${decision} — ${reason}`);

    return {
      decision,
      isAiSlop,
      hasPersonName,
      detectedNames: Array.isArray(result.detectedNames) ? result.detectedNames : [],
      reason,
      usedModel
    };
  } catch (err) {
    console.warn('[QualityChecker] OpenCode validation failed, falling back to heuristic validator:', err.message);
    const heuristic = heuristicQualityCheck({
      title: `${metadata.title || ''} ${metadata.originalTitle || ''}`,
      description: `${metadata.description || ''} ${metadata.originalDescription || ''}`,
      uploader: metadata.uploader || ''
    });
    return {
      ...heuristic,
      usedModel: `heuristic-fallback (${err.message.slice(0, 80)})`
    };
  } finally {
    // Clean up temporary extracted frames
    for (const framePath of sampleFrames) {
      if (fs.existsSync(framePath)) {
        try { fs.unlinkSync(framePath); } catch {}
      }
    }
  }
}

module.exports = {
  checkVideoQuality,
  extractSampleFrames,
  extractSubtitles,
  heuristicQualityCheck
};
